#!/usr/bin/env python3
"""Weekly Proxmox inventory job (run from a machine whose ssh config has an alias for every Proxmox host):
  1. read-only snapshot of every host (bin/proxmox_inventory.py) into fleet-state/inventory/proxmox-snapshot.json
  2. regenerate the tables in the docs that carry a `GENERATED:proxmox-inventory` block (docdrift gen), so VM sizes are never typed by hand
  3. check the documentation against the inventory (bin/inventory_check.py): an undocumented host, a wrong "<N> Proxmox hosts", a NEW guest nobody wrote down
  4. when the check is clean the snapshot becomes the baseline (inventory/proxmox-baseline.json); while it is not, the baseline stays, so the finding does not go away by itself
  5. commit the changed files to fleet-state master ([skip ci]); open or update ONE GitHub issue while there are findings and close it when there are none; show a macOS notification
Files in fleet-state/inventory/: proxmox-hosts.json (id + ssh alias per host), proxmox-snapshot.json, proxmox-baseline.json, inventory-allow.json (optional: {"guests": [...], "hosts": [...]}).

usage: inventory_weekly.py --fleet-state <clone dir named fleet-state> [--no-push] [--no-issue]
Exit status: 0 clean, 1 findings or an unreadable host."""
import argparse, glob, importlib.util, json, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ISSUE_TITLE = "Docs drift: Proxmox inventory vs documentation"
ID = ["-c", "user.name=Claude Code", "-c", "user.email=noreply@anthropic.com"]


def load_mod(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m


P, C = load_mod("proxmox_inventory"), load_mod("inventory_check")


def git(d, *a, check=True):
    r = subprocess.run(["git", "-C", d] + list(a), capture_output=True, text=True)
    if check and r.returncode:
        raise RuntimeError("git %s: %s" % (" ".join(a[:3]), (r.stderr or r.stdout).strip()[:200]))
    return r.stdout.strip()


def read_json(p):
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def write_json(p, d):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        json.dump(d, f, indent=1, sort_keys=True)
        f.write("\n")


def same(a, b):
    strip = lambda s: {k: v for k, v in (s or {}).items() if k != "taken_at"}
    return strip(a) == strip(b)


def docs_text(fs):
    paths = [os.path.join(fs, n) for n in ("OPS.md", "RUNBOOK.md", "PLACEMENT-ARCHITECTURE.md", "BUILDER-POOL.md", "README.md")] + glob.glob(os.path.join(fs, "docs", "**", "*.md"), recursive=True)
    out = []
    for p in paths:
        if os.path.exists(p):
            with open(p, errors="replace") as f:
                out.append(f.read())
    return out


def issue_body(findings):
    lines = ["The weekly Proxmox inventory check found documentation that does not match the fleet:", ""]
    lines += ["- **%s** %s: %s" % (f["kind"], f.get("host") or f.get("guest", ""), f["detail"]) for f in findings]
    lines += ["", "Fix: describe the host or guest in `OPS.md` (or the relevant doc). If it is deliberate, add its id or name to `inventory/inventory-allow.json`.",
              "The baseline stays where it is until the check is clean, so this issue closes itself on the next clean run.", "", "Generated by `bin/inventory_weekly.py` (services-registry)."]
    return "\n".join(lines)


def handle_issue(repo, findings):
    if not shutil.which("gh"):
        return "gh not found: issue not updated"
    q = subprocess.run(["gh", "issue", "list", "--repo", repo, "--state", "open", "--search", "in:title " + ISSUE_TITLE, "--json", "number,title", "--jq", ".[] | select(.title==\"%s\") | .number" % ISSUE_TITLE], capture_output=True, text=True)
    num = q.stdout.split()[0] if q.returncode == 0 and q.stdout.split() else None
    if findings:
        if num:
            subprocess.run(["gh", "issue", "edit", num, "--repo", repo, "--body", issue_body(findings)], capture_output=True, text=True)
            return "issue #%s updated" % num
        r = subprocess.run(["gh", "issue", "create", "--repo", repo, "--title", ISSUE_TITLE, "--body", issue_body(findings)], capture_output=True, text=True)
        return "issue opened: " + (r.stdout.strip().splitlines() or ["?"])[-1]
    if num:
        subprocess.run(["gh", "issue", "close", num, "--repo", repo, "--comment", "The weekly check is clean again."], capture_output=True, text=True)
        return "issue #%s closed" % num
    return "no issue needed"


def notify(text):
    if sys.platform == "darwin" and shutil.which("osascript"):
        subprocess.run(["osascript", "-e", 'display notification "%s" with title "Docs drift"' % text.replace('"', "'")[:200]], capture_output=True, text=True)


def run(fs, take=P.take, push=True, issue=True, remote="origin", branch="master", repo_slug="baditaflorin/fleet-state"):
    git(fs, "fetch", "-q", remote)
    git(fs, "checkout", "-q", "-B", branch, "%s/%s" % (remote, branch))
    inv = os.path.join(fs, "inventory")
    hosts = read_json(os.path.join(inv, "proxmox-hosts.json"))
    if not hosts:
        raise SystemExit("no %s/proxmox-hosts.json" % inv)
    snap, bad = take(hosts)
    if bad:  # a partly unreadable snapshot would blank hosts in the docs: keep everything as it is and say so
        findings = [dict(kind="host_unreadable", host=h, detail=v["error"]) for h, v in snap["hosts"].items() if "error" in v]
        report = dict(findings=findings, committed=False, issue=handle_issue(repo_slug, findings) if issue else "skipped")
        print(json.dumps(report)); return 1, report
    snap_p, base_p = os.path.join(inv, "proxmox-snapshot.json"), os.path.join(inv, "proxmox-baseline.json")
    old, base = read_json(snap_p), read_json(base_p)
    if old is None or not same(old, snap):
        write_json(snap_p, snap)
    allow = read_json(os.path.join(inv, "inventory-allow.json")) or {}
    commits = []
    git(fs, "add", "inventory")
    if git(fs, "status", "--porcelain", "inventory"):
        git(fs, *ID, "commit", "-q", "-m", "chore(inventory): weekly Proxmox snapshot [skip ci]")
        commits.append("snapshot")
    # tables: the generator reads the COMMITTED snapshot
    parent = os.path.dirname(os.path.abspath(fs))
    if os.path.basename(os.path.abspath(fs)) == "fleet-state":
        with_block = []
        for p in glob.glob(os.path.join(fs, "*.md")):
            with open(p, errors="replace") as f:
                if "GENERATED:proxmox-inventory" in f.read():
                    with_block.append(p)
        if with_block:
            subprocess.run([sys.executable, os.path.join(HERE, "docdrift.py"), "--repos", parent, "--ref", "HEAD", "gen", "--write"] + with_block, capture_output=True, text=True)
    if git(fs, "status", "--porcelain", "--", "*.md"):
        git(fs, "add", "-A", "--", "*.md")
        git(fs, *ID, "commit", "-q", "-m", "docs(inventory): regenerate the Proxmox guest tables [skip ci]")
        commits.append("tables")
    findings = C.check(snap, docs_text(fs), base if base is not None else snap, allow)
    if not findings and (base is None or not same(base, snap)):
        write_json(base_p, snap)
        git(fs, "add", "inventory")
        git(fs, *ID, "commit", "-q", "-m", "chore(inventory): the documentation matches the inventory; update the baseline [skip ci]")
        commits.append("baseline")
    pushed = False
    if commits and push:
        p = subprocess.run(["git", "-C", fs, "push", "-q", remote, "HEAD:" + branch], capture_output=True, text=True)
        if p.returncode:
            git(fs, "pull", "-q", "--rebase", remote, branch)
            git(fs, "push", "-q", remote, "HEAD:" + branch)
        pushed = True
    msg = handle_issue(repo_slug, findings) if issue else "skipped"
    if findings:
        notify("%d Proxmox inventory finding(s): see the fleet-state issue" % len(findings))
    report = dict(findings=findings, commits=commits, pushed=pushed, issue=msg)
    print(json.dumps(report))
    return (1 if findings else 0), report


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--fleet-state", required=True); ap.add_argument("--no-push", action="store_true"); ap.add_argument("--no-issue", action="store_true"); ap.add_argument("--report")
    a = ap.parse_args(argv)
    rc, report = run(a.fleet_state, push=not a.no_push, issue=not a.no_issue)
    if a.report:
        write_json(a.report, report)
    return rc


if __name__ == "__main__":
    sys.exit(main())
